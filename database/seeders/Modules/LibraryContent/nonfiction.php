Many people say they would like to read more but simply do not have time. They imagine reading as something that needs a quiet evening, a comfortable chair and an uninterrupted hour. Those evenings are rare, so the books stay unread.

There is another way. Reading in short bursts of five, ten or fifteen minutes can fit into the gaps of a normal day: on a bus, in a queue, while waiting for food or a meeting. These gaps already exist. The question is only how we use them.

## Small sessions are easier to start

The hardest part of any habit is starting. A plan to "read for an hour" can feel heavy, and it is easy to postpone. A plan to "read one page" feels light. Once you begin, you often continue longer than you planned, but even if you stop after one page, you have still read.

## Regular beats rare

Reading a little every day keeps a story or an idea fresh in your mind. You remember the characters, the argument, the last point the author made. When reading happens only once in a while, you often need to go back and reread just to remember where you were.

## Natural stopping points help memory

Short sessions tend to end at clear points: the end of a section, a chapter or an article. Pausing there gives your mind a moment to settle what it has just read. Many readers find it useful to think for a few seconds about the main idea before closing the book.

## How to make short bursts work

Keep reading material ready. A book in your bag or a reading app on your phone means you never have to search for something when a gap appears.

Choose the right kind of text. Short chapters, essays, articles and stories suit brief sessions well. Very dense material may need longer, quieter time.

