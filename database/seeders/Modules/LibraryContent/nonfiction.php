Every queue, no matter where it appears, has the same basic parts.

## Arrivals

First, there are arrivals: people coming to join the line. We often describe this with an arrival rate, the average number of people who arrive in a certain amount of time. For example, "twenty people per hour". Arrivals are rarely perfectly even. Three people may come at once, then nobody for ten minutes.

## Service

Second, there is service: the work done at the counter. The service rate is the average number of people one counter can finish in a given time. If a clerk spends about five minutes with each person, that clerk can serve about twelve people per hour.

## The waiting line itself

Between arrival and service is the line. It grows when people arrive faster than they are served, and shrinks when service is faster than arrivals.

## The golden rule

Here is the most important idea in this book: if, on average, people arrive faster than they can be served, the line will keep growing. It does not matter how patient everyone is. Twenty arrivals per hour and twelve services per hour means the line gets longer, hour after hour, until the office closes.

Even when service is a little faster than arrivals, lines still form, because arrivals come in bursts. A counter that is busy ninety percent of the time will often have a noticeable queue, while one that is busy half of the time usually feels calm. This is why adding just one extra counter at a busy time can make such a big difference.

> A queue is not a sign that people are slow. It is a sign that arrivals and service are out of balance, at least for a while.

