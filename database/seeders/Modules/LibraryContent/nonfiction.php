## Three kingdoms in one valley

For several centuries, the valley was ruled by the Malla kings. In the fifteenth century, after the reign of King Yaksha Malla, the valley gradually divided into separate kingdoms based in Kathmandu, Patan and Bhaktapur. The three courts competed with each other, and much of that competition was expressed through building: temples, palaces, courtyards and fountains, each city trying to outshine the others. Much of the architecture visitors admire today dates from the later Malla period.

