Nepal's calendar is full of festivals. Many follow the lunar calendar, so their dates shift from year to year in the Western calendar. Here is a short introduction to five of the best known.

## Dashain

Dashain is the longest and most widely celebrated festival in Nepal, usually falling in late September or October. It lasts for fifteen days and celebrates the victory of the goddess Durga over the demon Mahishasura, a symbol of good triumphing over evil.

On the first day, families plant barley seeds to grow jamara, golden-yellow shoots. On the tenth day, Vijaya Dashami, elders place tika, a mixture of rice, yoghurt and red colour, on the foreheads of younger relatives, along with jamara, and give blessings. People travel long distances to be home for this moment. Kites fill the sky, and bamboo swings are built in villages.

## Tihar

Tihar, also called Deepawali, comes a few weeks after Dashain and lasts five days. Each day honours something different: crows, dogs, and cows, followed by the worship of Laxmi, the goddess of wealth, when homes are lit with oil lamps and candles. Groups of young people go from house to house singing deusi and bhailo songs.

The final day is Bhai Tika, when sisters place colourful tika on their brothers' foreheads and give garlands, praying for their long life. Among the Newar community, Tihar also includes Mha Puja, a ritual of honouring one's own body and self.

## Holi

Holi, known in Nepal as Fagu Purnima, is the festival of colours, held on the full moon of the month of Fagun, usually in March. People throw coloured powder and water at each other in the streets, and friends and strangers alike end the day covered in bright colours. In the hills and Kathmandu it is usually celebrated a day before the Terai.

## Teej

Teej is a festival celebrated mainly by Hindu women, usually in August or September. Women dress in red, gather to sing and dance, and many observe a fast. The festival is associated with the goddess Parvati and her devotion to Lord Shiva, and women pray for the wellbeing of their families and for marital happiness. Temples, especially Pashupatinath in Kathmandu, become crowded with worshippers.

## Indra Jatra

Indra Jatra is a major festival of Kathmandu, celebrated over eight days around September. It honours Indra, the god of rain, and marks the end of the monsoon. A tall wooden pole is raised near Hanuman Dhoka at the start, masked dances such as the Lakhe dance fill the streets, and the Kumari, the living goddess, is carried through the old city in a chariot procession.

> Festivals are the calendar's way of reminding a community who it is.

Each festival has many local customs that vary from place to place and family to family. Together, they show the rich mix of faiths, cultures and communities that make up Nepal.
